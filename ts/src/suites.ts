/**
 * `MLKEM768-X25519`: ML-KEM-768 with the Curve25519 nominal group.
 *
 * `draft-irtf-cfrg-concrete-hybrid-kems-04` section 4.2. Identical to X-Wing
 * (`draft-connolly-cfrg-xwing-kem-10`), down to the six byte label.
 */
export const MLKEM768_X25519: HybridKemSuite = makeSuite(
  'MLKEM768-X25519',
  Uint8Array.from([0x5c, 0x2e, 0x2f, 0x2f, 0x5e, 0x5c]),
  'cfrg-concrete-hybrid-kems',
  MLKEM768,
  CURVE25519,
);

/**
 * `MLKEM1024-P384`: ML-KEM-1024 with the P-384 nominal group.
 *
 * `draft-irtf-cfrg-concrete-hybrid-kems-04` section 4.3. Label
 * `MLKEM1024-P384`.
 */
export const MLKEM1024_P384: HybridKemSuite = makeSuite(
  'MLKEM1024-P384',
  encoder.encode('MLKEM1024-P384'),
  'cfrg-concrete-hybrid-kems',
  MLKEM1024,
  P384_GROUP,
);

/**
 * `MLKEM1024-X25519`: ML-KEM-1024 with the Curve25519 nominal group.
 *
 * **Specified by this project and by nobody else.** See
 * `docs/mlkem1024-x25519.md`. Category 5 post-quantum without a NIST curve,
 * at the cost of a traditional half that is not level matched and a suite
 * that no standards body has reviewed.
 *
 * The label is namespaced rather than the bare name `MLKEM1024-X25519`: the
 * hybrid KEM label registry is managed and suffix free, this suite cannot be
 * in it, and a future registration of the bare name for a different
 * construction would make two implementations derive different secrets from
 * the same label with no diagnosable error.
 */
export const MLKEM1024_X25519: HybridKemSuite = makeSuite(
  'MLKEM1024-X25519',
  encoder.encode('quantakrypto.com/hybrid-kem/MLKEM1024-X25519/v1'),
  'this-project-only',
  MLKEM1024,
  CURVE25519,
);

/** Every suite, keyed by name. */
export const SUITES: Readonly<Record<SuiteName, HybridKemSuite>> = Object.freeze(
  {
    'MLKEM768-P256': MLKEM768_P256,
    'MLKEM768-X25519': MLKEM768_X25519,
    'MLKEM1024-P384': MLKEM1024_P384,
    'MLKEM1024-X25519': MLKEM1024_X25519,
  },
);

/**
 * Look a suite up by the name its specification uses.
 *
 * @throws {SuiteError} if there is no such suite. It throws rather than
 *   returning `undefined` because a silently missing suite in a protocol
 *   negotiation is worse than a loud one.
 */
export function getSuite(name: string): HybridKemSuite {
  const suite = (SUITES as Record<string, HybridKemSuite | undefined>)[name];
  if (suite === undefined) {
    throw new SuiteError('unknown-suite', `unknown hybrid KEM suite: ${name}`);
  }
  return suite;
}
