/**
 * Complete hybrid KEM suites, layered on the combiner.
 *
 * The combiner in the package root is a pure function of bytes: it derives
 * the shared secret once you already have both components' outputs. Getting
 * those outputs right is the other half of the problem, and it is the half
 * where the positional mistakes actually happen. A suite closes that gap: it
 * is key generation, encapsulation and decapsulation as one primitive, with
 * no six-argument call for a caller to misorder.
 *
 * # What is specified here, and by whom
 *
 * Three of the four suites are specified by the CFRG in
 * `draft-irtf-cfrg-concrete-hybrid-kems-04` section 4, which also publishes
 * test vectors in its Appendix B. Those vectors are the external anchor:
 * they were produced by the specification's authors, not by this project,
 * and the conformance suite runs all thirty of them in TypeScript and in
 * Rust.
 *
 * - {@link MLKEM768_P256}
 * - {@link MLKEM768_X25519}, which is X-Wing
 * - {@link MLKEM1024_P384}
 *
 * The fourth, {@link MLKEM1024_X25519}, is specified by this project and by
 * nobody else. It is written up in `docs/mlkem1024-x25519.md`, including the
 * argument against using it. No external test vectors exist for it, because
 * no external specification of it exists. Its vectors are regression pins
 * generated by these implementations, and they establish only that the two
 * languages agree and that the bytes have not drifted.
 *
 * Every suite carries a {@link Provenance} so that the distinction is
 * available at runtime and not only in prose.
 *
 * # The construction
 *
 * All four use the CG framework of `draft-irtf-cfrg-hybrid-kems-12` section
 * 5.5: the C2PRI combiner with a nominal group as the traditional component,
 * SHAKE256 as the PRG and SHA3-256 as the KDF. Every suite's shared secret is
 * this package's own `combineC2pri('sha3-256', ...)`.
 *
 * # What is not promised
 *
 * The same disclaimer as the rest of the package, and one more. The
 * arithmetic is `@noble/post-quantum`'s and `@noble/curves`'; this module's
 * code is the framework around it, implemented from the drafts. That
 * framework has had no external cryptographic review.
 *
 * @packageDocumentation
 */

