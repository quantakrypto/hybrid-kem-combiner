//! Complete hybrid KEM suites, layered on the combiner.
//!
//! The combiner in the crate root is a pure function of bytes: it derives the
//! shared secret once you already have both components' outputs. Getting
//! those outputs right is the other half of the problem, and it is the half
//! where the positional mistakes actually happen. A suite closes that gap: it
//! is key generation, encapsulation and decapsulation as one primitive, with
//! no six-argument call for a caller to misorder.
//!
//! # What is specified here, and by whom
//!
//! Three of the four suites are **specified by the CFRG** in
//! `draft-irtf-cfrg-concrete-hybrid-kems-04` section 4, which also publishes
//! test vectors in its Appendix B. Those vectors are the external anchor for
//! this module: they were produced by the specification's authors, not by
//! this project, and the conformance suite runs all thirty of them in Rust
//! and in TypeScript.
//!
//! - [`Suite::MlKem768P256`]
//! - [`Suite::MlKem768X25519`], which is X-Wing
//! - [`Suite::MlKem1024P384`]
//!
//! The fourth, [`Suite::MlKem1024X25519`], is **specified by this project and
//! by nobody else**. It is written up in `docs/mlkem1024-x25519.md` in the
//! repository, including the argument against using it. No external test
//! vectors exist for it, because no external specification of it exists. Its
//! vectors are regression pins generated by these implementations, and they
//! establish only that Rust and TypeScript agree and that the bytes have not
//! drifted. They establish nothing about whether the pairing is a good idea.
//!
//! [`Suite::provenance`] carries that distinction at runtime, and
//! [`Provenance`] documents it.
//!
//! # The construction
//!
//! All four use the **CG framework** of `draft-irtf-cfrg-hybrid-kems-12`
//! section 5.5: the C2PRI combiner with a nominal group as the traditional
//! component, SHAKE256 as the PRG and SHA3-256 as the KDF. In terms of this
//! crate's own API, every suite's shared secret is
//!
//! ```text
//! combine_c2pri(Kdf::Sha3_256, { ss_PQ, ss_T, ct_T, ek_T, label }, out)
//! ```
//!
//! The C2PRI form drops the ML-KEM ciphertext and encapsulation key from the
//! derivation, which is sound because ML-KEM is ciphertext second preimage
//! resistant. That is not this module's assumption to make lightly, and it is
//! not made lightly: it is the assumption the CFRG draft itself makes for all
//! three of its suites (section 5 of `concrete-hybrid-kems-04`, which cites
//! the X-Wing analysis for ML-KEM's C2PRI property). See
//! [`crate::C2priAssertion`].
//!
//! # Example
//!
//! ```
//! use hybrid_kem_combiner::suites::Suite;
//!
//! let suite = Suite::MlKem768X25519;
//!
//! // A seed you generated from a cryptographically secure source. With the
//! // `os-rng` feature, `suite.generate_key_pair()` does this for you.
//! let seed = [0x42u8; 32];
//! let recipient = suite.derive_key_pair(&seed).unwrap();
//!
//! // The sender holds only the encapsulation key.
//! let eseed = [0x17u8; 64];
//! let sent = suite
//!     .encapsulate_derand(recipient.encapsulation_key(), &eseed)
//!     .unwrap();
//!
//! // The recipient recovers the same secret from the ciphertext.
//! let received = suite
//!     .decapsulate(recipient.decapsulation_key(), sent.ciphertext())
//!     .unwrap();
//!
//! assert_eq!(sent.shared_secret(), received.as_slice());
//! ```
//!
//! # What is not promised
//!
//! The same disclaimer as the rest of the crate, and one more. The suites are
//! assembled from `libcrux-ml-kem`, `p256`, `p384` and `x25519-dalek`, and
//! this module's own code is the framework around them: the PRG expansion,
//! the seed split, the scalar sampling, the encodings and the combiner call.
//! That framework has had no external cryptographic review. The component
//! implementations have their own review status, which is theirs and not
//! this project's to claim.

